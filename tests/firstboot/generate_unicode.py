"""Generate the JS UX mirror from local ICU's Unicode 17.0 properties.
No downloads. ICU is a generation tool, not a new greeter runtime dependency.
Rust char uses Lowercase, Uppercase, Number and Alphabetic (Unicode 17.0).
"""
import ctypes
import ctypes.util
import sys


def generate():
    library = ctypes.CDLL(ctypes.util.find_library('icuuc'))
    suffix = next(str(v) for v in range(100, 60, -1) if hasattr(library, 'u_getUnicodeVersion_' + str(v)))
    version = (ctypes.c_uint8 * 4)()
    getattr(library, 'u_getUnicodeVersion_' + suffix)(version)
    if tuple(version) != (17, 0, 0, 0):
        raise RuntimeError('Unicode 17.0.0 is required; do not silently regenerate from another release')
    binary = getattr(library, 'u_hasBinaryProperty_' + suffix)
    binary.argtypes = [ctypes.c_int32, ctypes.c_int]
    binary.restype = ctypes.c_uint8
    category = getattr(library, 'u_charType_' + suffix)
    category.argtypes = [ctypes.c_int32]
    category.restype = ctypes.c_int8
    # ICU UProperty: Alphabetic=0, Lowercase=22, Uppercase=30.
    # UCharCategory: Nd/Nl/No=9/10/11; Zl/Zp/Cc/Cf=13/14/15/16.
    def mask(cp):
        kind = category(cp)
        numeric = kind in (9, 10, 11)
        return (int(binary(cp, 22)) | (int(binary(cp, 30)) << 1) |
                (int(numeric) << 2) | (int(not (binary(cp, 0) or numeric)) << 3) |
                (int(kind in (13, 14, 15, 16)) << 4))
    ranges = []
    start, previous = 0, mask(0)
    for cp in range(1, 0x110001):
        value = mask(cp) if cp < 0x110000 else -1
        if value != previous:
            if previous:
                ranges.append((start, cp - 1, previous))
            start, previous = cp, value
    lines = ['.pragma library', '', '// Generated by tests/firstboot/generate_unicode.py; Unicode 17.0.0.',
             '// Bits: Lowercase=1, Uppercase=2, Number=4, !Alphanumeric=8, Cc/Cf/Zl/Zp=16.',
             '// Unicode data licence and provenance: UNICODE-NOTICE.txt. Do not hand-edit.',
             'var ranges = [']
    lines += ['    0x%x, 0x%x, %d,' % row for row in ranges]
    lines += ['];', '', 'function mask(codepoint) {', '    let low = 0, high = ranges.length / 3 - 1;',
              '    while (low <= high) {', '        const mid = (low + high) >> 1;',
              '        const offset = mid * 3;', '        if (codepoint < ranges[offset]) high = mid - 1;',
              '        else if (codepoint > ranges[offset + 1]) low = mid + 1;',
              '        else return ranges[offset + 2];', '    }', '    return 0;', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    sys.stdout.write(generate())
