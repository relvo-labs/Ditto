#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct ProfileDocument {
    pub schema_version: u32,
    pub entries: Vec<EntrySpec>,
    /// slot name → entry id.
    pub slots: BTreeMap<String, String>,
    pub layout: LayoutIntent,
    pub appearance: Appearance,
    #[serde(default)]
    pub shortcuts: Vec<ShortcutBinding>,
    pub avatar: AvatarSettings,
}

impl ProfileDocument {
    pub fn entry(&self, entry_id: &str) -> Option<&EntrySpec> {
        self.entries.iter().find(|entry| entry.entry_id == entry_id)
    }

    pub fn entry_mut(&mut self, entry_id: &str) -> Option<&mut EntrySpec> {
        self.entries
            .iter_mut()
            .find(|entry| entry.entry_id == entry_id)
    }

    pub fn slot_entry(&self, slot: &str) -> Option<&EntrySpec> {
        self.slots.get(slot).and_then(|id| self.entry(id))
    }

    pub fn to_value(&self) -> Value {
        serde_json::to_value(self).expect("profile document serializes")
    }

    pub fn digest(&self) -> String {
        crate::jcs::digest(&self.to_value())
    }
}

